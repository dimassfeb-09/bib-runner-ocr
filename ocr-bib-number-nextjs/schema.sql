-- Enable pgcrypto extension for gen_random_uuid() if not already enabled
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- 1. ADMIN TABLE
CREATE TABLE IF NOT EXISTS admins (
    id SERIAL PRIMARY KEY,
    username VARCHAR(100) UNIQUE NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 2. EVENTS TABLE
CREATE TABLE IF NOT EXISTS events (
    id SERIAL PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    event_date DATE NOT NULL,
    location VARCHAR(255),
    bundle_price DECIMAL(12, 2) DEFAULT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 3. PHOTOS TABLE
CREATE TABLE IF NOT EXISTS photos (
    id SERIAL PRIMARY KEY,
    event_id INT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    original_url TEXT NOT NULL,      -- URL to private bucket in Supabase Storage
    watermark_url TEXT NOT NULL,     -- URL to public bucket in Supabase Storage
    price DECIMAL(12, 2) DEFAULT NULL,
    uploaded_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 4. BIB_NUMBERS TABLE
CREATE TABLE IF NOT EXISTS bib_numbers (
    id SERIAL PRIMARY KEY,
    event_id INT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    number VARCHAR(50) NOT NULL,
    price DECIMAL(12, 2) DEFAULT NULL, -- Custom bundle price for this BIB in this event
    -- Prevent duplicate bib numbers in the same event
    CONSTRAINT unique_event_bib UNIQUE (event_id, number)
);

-- 5. PHOTO_BIBS PIVOT TABLE (Many-to-Many)
CREATE TABLE IF NOT EXISTS photo_bibs (
    photo_id INT NOT NULL REFERENCES photos(id) ON DELETE CASCADE,
    bib_number_id INT NOT NULL REFERENCES bib_numbers(id) ON DELETE CASCADE,
    bbox INTEGER[] DEFAULT NULL,
    PRIMARY KEY (photo_id, bib_number_id)
);

-- 6. ORDERS TABLE (Midtrans Transactions)
CREATE TABLE IF NOT EXISTS orders (
    id VARCHAR(100) PRIMARY KEY, -- Transaction ID generated by system or Midtrans
    buyer_email VARCHAR(255) NOT NULL,
    payment_status VARCHAR(50) NOT NULL DEFAULT 'pending', -- pending, settlement, expire, deny
    total_amount DECIMAL(12, 2) NOT NULL,
    download_token UUID UNIQUE NOT NULL DEFAULT gen_random_uuid(), -- Secure token for guest download access
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 7. ORDER_ITEMS TABLE (Details of photos in each order)
CREATE TABLE IF NOT EXISTS order_items (
    id SERIAL PRIMARY KEY,
    order_id VARCHAR(100) NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    photo_id INT REFERENCES photos(id) ON DELETE SET NULL -- If photo is deleted, keep order history
);

-- 8. SETTINGS TABLE (Config key-value store)
CREATE TABLE IF NOT EXISTS settings (
    key VARCHAR(100) PRIMARY KEY,
    value TEXT NOT NULL
);

-- 9. UNRECOGNIZED BIBS TABLE (For low confidence OCR detections)
CREATE TABLE IF NOT EXISTS unrecognized_bibs (
    id SERIAL PRIMARY KEY,
    photo_id INT NOT NULL REFERENCES photos(id) ON DELETE CASCADE,
    suggested_number VARCHAR(50) NOT NULL,
    confidence_score DECIMAL(5, 4) NOT NULL, -- E.g. 0.4500
    status VARCHAR(20) NOT NULL DEFAULT 'pending', -- pending, accepted, rejected
    bbox INTEGER[] DEFAULT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- =========================================================================
-- INDEXES FOR QUERY OPTIMIZATION
-- =========================================================================

-- Speed up search by bib number
CREATE INDEX IF NOT EXISTS idx_bib_numbers_number ON bib_numbers(number);

-- Speed up search by download token
CREATE INDEX IF NOT EXISTS idx_orders_download_token ON orders(download_token);

-- Speed up lookup by buyer email
CREATE INDEX IF NOT EXISTS idx_orders_buyer_email ON orders(buyer_email);

-- Speed up query on unrecognized bibs by status
CREATE INDEX IF NOT EXISTS idx_unrecognized_bibs_status ON unrecognized_bibs(status);
